export type IconName = keyof typeof ICONS;

const COLOR: Record<string, string> = { '#': 'currentColor', '+': 'var(--ic-2, currentColor)', '*': 'var(--ic-3, #fff)' };

function rects(rows: readonly string[]) {
  const out: { x: number; y: number; w: number; c: string }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (!COLOR[ch]) {
        x++;
        continue;
      }
      let x2 = x + 1;
      while (x2 < row.length && row[x2] === ch) x2++;
      out.push({ x, y, w: x2 - x, c: COLOR[ch] });
      x = x2;
    }
  });
  return out;
}

const CACHE = new Map<IconName, ReturnType<typeof rects>>();

export const PixelIcon = memo(function PixelIcon({ name, size = 24, className, title }: { name: IconName; size?: number; className?: string; title?: string }) {
  let r = CACHE.get(name);
  if (!r) {
    r = rects(ICONS[name]);
    CACHE.set(name, r);
  }
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
    >
      {title && <title>{title}</title>}
      {r.map((p, i) => (
        <rect key={i} x={p.x} y={p.y} width={p.w} height={1} fill={p.c} />
      ))}
    </svg>
  );
});
